"""Export a compact offline replay; no JS reimplementation of the controller.

Run after `perfusion-lab benchmark --out results` from the repository root.
Every third time sample is kept for display, plus the final sample. All summary
metrics remain the original full-resolution Python metrics.
"""
import json
from pathlib import Path

root=Path(__file__).resolve().parents[1]
trajectories=json.loads((root/'results/trajectories.json').read_text())
summary=json.loads((root/'results/summary.json').read_text())
keys={'t':'time','do2':'do2','monitor':'measured_do2','reservoir':'reservoir',
      'pressure':'pressure','infeasible':'infeasible','fault':'fault'}
runs={}
for name,result in trajectories.items():
    indices=sorted(set(range(0,len(result['rows']),3))|{len(result['rows'])-1})
    sampled=[result['rows'][i] for i in indices]
    run={k:[round(row[field],4) if isinstance(row[field],float) else row[field]
            for row in sampled] for k,field in keys.items()}
    run['metrics']=result['metrics']
    runs[name]=run
# Scenario chunks keep both browser parsing and source uploads modest in size.
# All scripts are local and load in a fixed order, so file:// replay still works.
(root/'web/data.js').write_text('/* Generated by examples/build_web.py; synthetic data. */\nconst PERFUSION = '+
    json.dumps(dict(protocol=summary['protocol'],comparisons=summary['comparisons'],runs={}),separators=(',',':'))+';\n')
for scenario in summary['protocol']['scenarios']:
    subset = {key: value for key, value in runs.items() if key.startswith(scenario+'/')}
    (root/f'web/data-{scenario}.js').write_text(
        '/* Generated synthetic replay. */\nObject.assign(PERFUSION.runs,'+
        json.dumps(subset,separators=(',',':'))+');\n')
print(f'Exported {len(runs)} representative trajectories.')
